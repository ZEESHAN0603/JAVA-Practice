package Phase3;

public class FormattedOP {
    public static void main(String[] args) {
        System.out.format("%-7s %-5s %-5s%n","Name", "Goals", "Cups"); // %7s means %s- string, 7 means 7 space after other word
        System.out.format("%-7s %-5d %-5d%n","Messi", 916, 2); // %n is new line
    }
}
